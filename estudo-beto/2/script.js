const campo1 = document.querySelector('#campo1')
const campo2 = document.querySelector('#campo2')
const btn_converter = document.querySelector('#converter')

function conversao(){
    if (campo1.value.trim() == '' && campo2.value.trim() == '') return
    let listaletras = ''
    for (const letra of campo1.value.toUpperCase()){
        if (letra == ' '){
            listaletras += '00100000'
        } else listaletras += listabinario[letra]
    }
    campo2.value = listaletras
}

btn_converter.addEventListener('click',conversao)